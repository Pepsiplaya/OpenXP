"""Write the OpenXP UI translations from tools/locale/<lang>/ui.json into
locale/<file>.lua, between the OpenXP UI markers.

Keys and values are raw Lua string bodies (escapes such as \\n and \\" are kept).

    python3 tools/locale/build_ui_locale.py es esES
"""
import json, re, sys

BEGIN = "-- BEGIN OpenXP UI (generated by tools/locale/build_ui_locale.py)"
END = "-- END OpenXP UI"


def quote(raw):
    # escape any double quote that is not already escaped
    out, i = [], 0
    while i < len(raw):
        c = raw[i]
        if c == "\\" and i + 1 < len(raw):
            nxt = raw[i + 1]
            out.append("'" if nxt == "'" else c + nxt)
            i += 2
            continue
        out.append('\\"' if c == '"' else c)
        i += 1
    return '"' + "".join(out) + '"'


def main(lang, locale):
    data = json.load(open(f"tools/locale/{lang}/ui.json", encoding="utf-8"))
    path = f"locale/{locale}.lua"
    src = open(path, encoding="utf-8").read()
    src = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", src, flags=re.S)
    lines = [BEGIN]
    for k in sorted(data):
        if k and data[k]:
            lines.append(f"L[{quote(k)}] = {quote(data[k])}")
    lines.append(END)
    src = src.rstrip("\n") + "\n\n" + "\n".join(lines) + "\n"
    open(path, "w", encoding="utf-8").write(src)
    print(path, len(lines) - 2, "strings")


if __name__ == "__main__":
    main(*sys.argv[1:3])
